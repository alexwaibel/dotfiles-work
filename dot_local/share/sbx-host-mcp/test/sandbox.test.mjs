test("mountless seed imports only the pinned committed revision and leaves the host checkout untouched", async t => {
  const paths = await fixture(t);
  const baseline = await git(paths.repo, "rev-parse", "HEAD");
  await writeFile(join(paths.repo, "untracked-secret"), "must not enter VM");
  const sandbox = createSandbox(paths.config);
  await sandbox.seed(123, { slug: "fresh", repo: "example-repo" });
  const state = await transferState(paths);
  assert.equal(await git(state.repoDir, "rev-parse", "HEAD"), baseline);
  assert.equal(await git(state.repoDir, "remote"), "");
  assert.equal(await git(paths.repo, "status", "--porcelain"), "?? untracked-secret");
  assert.deepEqual(await readdir(state.repoDir), [".git", "baseline.txt"]);
  const commands = (await readFile(join(paths.root, "sbx.log"), "utf8")).trim().split("\n").map(JSON.parse);
  const create = commands.find(value => value.command === "create");
  assert.equal(create.args.includes("--clone"), false);
  assert.equal(create.args.at(-1), "copilot");
  paths.env.FAKE_SBX_WARNING = "1";
  await writeJson(join(paths.state, "123.json"), { ...state, privateValue: "must-not-leak" });
  const inspected = await sandbox.inspect(123);
  assert.equal(inspected.sandboxStatus, "present");
  assert.equal(inspected.privateValue, undefined);
  await assert.rejects(sandbox.seed(123, { slug: "fresh", repo: "example-repo" }), /already exists/);
});

test("follow-up seed uses the remote PR revision, preserving previous state on failure", async t => {
  const paths = await fixture(t);
  const branch = "users/alwaibel/agent/123-followup";
  await git(paths.repo, "switch", "-qc", branch);
  const head = await commit(paths.repo, "pr.txt");
  await git(paths.repo, "push", "-qu", "origin", branch);
  await git(paths.repo, "switch", "-q", "master");
  const previous = { workItem: "123", repo: "example-repo", sandbox: "wi-123-vm", branch, hostWorktree: "/preserved", exportedCommit: "old" };
  await writeJson(join(paths.state, "123.json"), previous);
  const sandbox = createSandbox(paths.config);
  await assert.rejects(sandbox.seed(123, { slug: "followup", repo: "example-repo" }), /exported host work/);
  paths.env.FAKE_SBX_FAIL = "bootstrap";
  await assert.rejects(sandbox.seed(123, { slug: "followup", repo: "example-repo", reuseExistingBranch: true }), /fixture seed failed/);
  assert.deepEqual(await transferState(paths), previous);
  assert.deepEqual(await readdir(paths.env.FAKE_SBX_ROOT), []);
  delete paths.env.FAKE_SBX_FAIL;
  await sandbox.seed(123, { slug: "followup", repo: "example-repo", reuseExistingBranch: true });
  const state = await transferState(paths);
  assert.equal(state.baseSha, head);
  assert.equal(await git(state.repoDir, "rev-parse", "HEAD"), head);
  assert.equal(state.hostWorktree, undefined);
  assert.equal(await git(paths.repo, "branch", "--show-current"), "master");
});

test("private restore uses pinned package metadata, scripts-disabled process-scoped credentials, and Windows forwarding", async t => {
  const paths = await fixture(t);
  await commit(paths.repo, "package.json", '{"packageManager":"yarn@4.14.0"}');
  await commit(paths.repo, ".yarnrc.yml", 'npmRegistryServer: "https://pkgs.dev.azure.com/example/feed/npm/registry/"\nnpmAuthToken: "${ADO_NPM_TOKEN}"\n');
  await git(paths.repo, "push", "-q", "origin", "master");
  const powershell = join(paths.bin, "powershell.exe");
  await writeFile(powershell, '#!/usr/bin/env node\nconsole.log("package-read-token");\n', { mode: 0o700 });
  const windowsSbx = join(paths.bin, "sbx.exe");
  await copyFile(paths.env.SBX_WORK_SBX_BIN, windowsSbx);
  paths.env.SBX_WORK_SBX_BIN = windowsSbx;
  paths.env.SBX_WORK_POWERSHELL_BIN = powershell;
  paths.env.WSLENV = "EXISTING";
  await createSandbox(paths.config).seed(123, { slug: "private", repo: "example-repo" });
  const log = await readFile(join(paths.root, "sbx.log"), "utf8");
  assert.doesNotMatch(log, /package-read-token/);
  const calls = log.trim().split("\n").map(JSON.parse);
  const authorized = calls.filter(value => value.tokenPresent);
  assert.equal(authorized.length, 1);
  assert.equal(authorized[0].command, "exec");
  assert.equal(authorized[0].wslenv, "EXISTING:ADO_NPM_TOKEN");
  assert.ok(authorized[0].args.includes("YARN_ENABLE_SCRIPTS=false"));
  assert.ok(authorized[0].args.includes("npm_config_ignore_scripts=true"));
  assert.ok(authorized[0].args.includes("PNPM_CONFIG_IGNORE_SCRIPTS=true"));
  assert.deepEqual(authorized[0].args.slice(-3), ["yarn", "install", "--immutable"]);
  assert.equal(await readFile(join((await transferState(paths)).repoDir, ".yarn/install-state.gz"), "utf8"), "restored");
});

test("export and self-contained sync preserve exact SHAs without integrating host history", async t => {
  const paths = await fixture(t);
  const sandbox = createSandbox(paths.config);
  await sandbox.seed(123, { slug: "transfer", repo: "example-repo" });
  const state = await transferState(paths);
  const hostHead = await git(paths.repo, "rev-parse", "HEAD");
  const vmHead = await commit(state.repoDir, "followup.txt");
  const imported = await sandbox.export(123);
  assert.equal(imported.importedCommit, vmHead);
  assert.equal(await git(paths.repo, "rev-parse", imported.importedRef), vmHead);
  assert.equal(await git(paths.repo, "rev-parse", "HEAD"), hostHead);
  await commit(paths.repo, "upstream.txt");
  const reviewed = join(paths.root, "reviewed");
  await git(paths.repo, "worktree", "add", "-qb", "reviewed", reviewed, vmHead);
  await git(reviewed, "rebase", "master");
  const reviewedHead = await git(reviewed, "rev-parse", "HEAD");
  await git(paths.repo, "remote", "set-url", "origin", join(paths.root, "unavailable.git"));
  await writeFile(join(paths.repo, "uncommitted"), "preserve");
  assert.deepEqual(await sandbox.sync(123, reviewedHead), { syncedCommit: reviewedHead });
  assert.equal(await git(state.repoDir, "rev-parse", "HEAD"), reviewedHead);
  assert.equal(await readFile(join(paths.repo, "uncommitted"), "utf8"), "preserve");
  assert.equal(await git(paths.repo, "for-each-ref", "--format=%(refname)", "refs/sbx-work/transfers"), "");
  assert.deepEqual((await readdir(paths.state)).filter(name => name.startsWith("transfer-")), []);
});

test("failed, dirty, wrong-branch and corrupted transfers preserve checkout and verified metadata", async t => {
  const paths = await fixture(t);
  const sandbox = createSandbox(paths.config);
  await sandbox.seed(123, { slug: "guards", repo: "example-repo" });
  const state = await transferState(paths);
  const vmHead = await commit(state.repoDir, "change");
  await sandbox.export(123);
  const verified = await transferState(paths);
  for (const sha of [undefined, "HEAD", "a".repeat(40)]) await assert.rejects(sandbox.sync(123, sha));
  await writeFile(join(state.repoDir, "local"), "preserve");
  await assert.rejects(sandbox.sync(123, state.baseSha), /uncommitted/);
  await assert.rejects(sandbox.export(123), /uncommitted/);
  await rm(join(state.repoDir, "local"));
  await git(state.repoDir, "switch", "-qc", "unexpected");
  await assert.rejects(sandbox.sync(123, state.baseSha), /expected branch/);
  await assert.rejects(sandbox.export(123), /expected branch/);
  await git(state.repoDir, "switch", "-q", state.branch);
  paths.env.FAKE_SBX_CORRUPT = "1";
  await assert.rejects(sandbox.sync(123, state.baseSha));
  await assert.rejects(sandbox.export(123));
  delete paths.env.FAKE_SBX_CORRUPT;
  const replacement = join(paths.root, "replacement.bundle");
  await git(paths.repo, "bundle", "create", replacement, "master");
  paths.env.FAKE_SBX_REPLACEMENT = replacement;
  await assert.rejects(sandbox.export(123), /expected sandbox branch/);
  await assert.rejects(sandbox.sync(123, state.baseSha), /requested commit/);
  assert.deepEqual(await transferState(paths), verified);
  assert.equal(await git(state.repoDir, "rev-parse", "HEAD"), vmHead);
  assert.equal(await git(paths.repo, "for-each-ref", "--format=%(refname)", "refs/sbx-work/transfers"), "");
});

test("self-contained sync also supports existing shallow and disconnected VM histories", async t => {
  const paths = await fixture(t);
  const sandbox = createSandbox(paths.config);
  await sandbox.seed(123, { slug: "legacy", repo: "example-repo" });
  const state = await transferState(paths);
  await writeFile(join(state.repoDir, ".git/shallow"), `${state.baseSha}\n`);
  const followup = await commit(paths.repo, "new-host-history");
  await sandbox.sync(123, followup);
  assert.equal(await git(state.repoDir, "rev-parse", "HEAD"), followup);
  await git(state.repoDir, "switch", "-q", "--orphan", "disconnected");
  await commit(state.repoDir, "unrelated-history");
  await git(state.repoDir, "branch", "-M", state.branch);
  await sandbox.sync(123, followup);
  assert.equal(await git(state.repoDir, "rev-parse", "HEAD"), followup);
});

